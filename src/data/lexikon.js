/** Buchstabe für die A–Z-Leiste (Umlaute zum Grundbuchstaben). */
export function buchstabeVon(b) {
  if (b.buchstabe) return b.buchstabe;
  const c = b.begriff.trim().charAt(0).toUpperCase();
  return { Ä: "A", Ö: "O", Ü: "U" }[c] || c;
}

/** Begriffe alphabetisch, gruppiert nach Buchstaben. */
export function begriffeNachBuchstabe() {
  const sortiert = [...BEGRIFFE].sort((a, b) => a.begriff.localeCompare(b.begriff, "de"));
  const gruppen = new Map();
  for (const b of sortiert) {
    const l = buchstabeVon(b);
    if (!gruppen.has(l)) gruppen.set(l, []);
    gruppen.get(l).push(b);
  }
  return [...gruppen.entries()].sort(([a], [b]) => a.localeCompare(b, "de"));
}

/** Alias-ID -> Haupt-ID (für Anker aus älteren Links). */
export const ALIAS = Object.fromEntries(BEGRIFFE.flatMap((b) => (b.alias || []).map((a) => [a, b.id])));

/** Begriff nach id oder Alias-ID – undefined, wenn unbekannt. */
export const begriff = (id) => BEGRIFFE.find((b) => b.id === (ALIAS[id] || id));

/**
 * schema.org DefinedTerm für einen Lexikon-Begriff – dieselbe @id wie im
 * DefinedTermSet auf /wissen/lexikon, damit Fachseiten auf den Eintrag verweisen
 * können (z. B. /technik/parkregler). null, wenn der Begriff fehlt.
 */
export function definedTerm(id) {
  const b = begriff(id);
  if (!b) return null;
  return {
    "@type": "DefinedTerm",
    "@id": `${LEXIKON_URL}#${b.id}`,
    name: b.begriff,
    description: b.kurz,
    url: `${LEXIKON_URL}#${b.id}`,
    termCode: b.id,
    ...(b.synonyme?.length ? { alternateName: b.synonyme } : {}),
    inDefinedTermSet: { "@id": `${LEXIKON_URL}/#termset` },
  };
}
